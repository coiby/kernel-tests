# Include Beaker environment
. /usr/bin/rhts-environment.sh || exit 1
. /usr/share/beakerlib/beakerlib.sh || exit 1

PACKAGE="ipmitool"

rlJournalStart
    rlPhaseStartSetup
        rlAssertRpm $PACKAGE
        rlRun "TmpDir=\$(mktemp -d)" 0 "Creating tmp directory"
        rlRun "pushd $TmpDir"
    rlPhaseEnd

    rlPhaseStartTest
        VERSION_FROM_RPM=$(rpm -q ipmitool | sed -r 's/ipmitool\-([0-9\.]+).*?/\1/')
        VERSION_FROM_EXE=$(ipmitool -V | sed -r 's/ipmitool version ([0-9\.]+).*?/\1/')
        rlRun "[ \"$VERSION_FROM_RPM\" = \"$VERSION_FROM_EXE\" ]" 0 "Check, if version number from rpm -q matches the one from ipmitool -V"
    rlPhaseEnd

    rlPhaseStartCleanup
        rlRun "popd"
        rlRun "rm -r $TmpDir" 0 "Removing tmp directory"
    rlPhaseEnd
rlJournalPrintText
rlJournalEnd
